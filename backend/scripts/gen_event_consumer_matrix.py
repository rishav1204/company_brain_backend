#!/usr/bin/env python3
"""Generate event consumer matrix for PLATFORM_DATA_FLOWS documentation."""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HANDLERS = ROOT / "apps/api/app/modules/platform/events/consumers/handlers/legacy_handlers.py"
ROUTER = ROOT / "apps/api/app/services/event_consumers_router.py"
OUT = ROOT.parent / "docs" / "EVENT_CONSUMER_MATRIX.md"


def _extract_handler_events(path: Path) -> dict[str, list[str]]:
    text = path.read_text(encoding="utf-8")
    handlers: dict[str, list[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        m = re.match(r"def (_consume_\w+)\(", line)
        if m:
            current = m.group(1)
            handlers[current] = []
            continue
        if current and "event_type" in line:
            for ev in re.findall(r'"([a-z0-9_.]+)"', line):
                if "." in ev and ev not in handlers[current]:
                    handlers[current].append(ev)
    return handlers


def main() -> None:
    handlers = _extract_handler_events(HANDLERS)
    router_text = ROUTER.read_text(encoding="utf-8")
    lines = [
        "# Event Consumer Matrix",
        "",
        "Auto-generated by `backend/scripts/gen_event_consumer_matrix.py`.",
        "",
        "| Handler | Sample event types |",
        "|---------|-------------------|",
    ]
    for name in sorted(handlers):
        if not name.startswith("_consume"):
            continue
        events = handlers[name][:8]
        ev_str = ", ".join(f"`{e}`" for e in events) if events else "_(dynamic)_"
        wired = "yes" if name.replace("_consume_", "consume_") in router_text or name in router_text else "partial"
        lines.append(f"| `{name}` | {ev_str} | wired: {wired} |")
    lines.extend(["", "## M38 goal triggers", ""])
    goal_map = {
        "invoice.due": "collections_followup",
        "invoice.anomaly_detected": "ap_review",
        "invoice.duplicate_detected": "ap_review",
        "liquidity_alert.created": "treasury_advisory",
        "treasury.risk.detected": "treasury_advisory",
        "erp.period.close.requested": "period_close",
        "reconciliation.exception.created": "recon_review",
        "grn.confirmed": "inventory_received",
    }
    for ev, tmpl in sorted(goal_map.items()):
        lines.append(f"- `{ev}` → `{tmpl}`")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
